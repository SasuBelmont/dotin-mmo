export function getSkillsForPlayer(
  characterClass: CharacterClass,
  level: number,
  subclass?: string | null
): SkillInfo[] {
  const basic = ALL_SKILLS.find((s) => s.id === 'ataque_basico')!;

  if (level < 5 || !subclass) {
    // Nivel 1 a 4 o sin doctrina: solo ataque básico
    return [basic];
  }

  const sLower = (subclass || '').toLowerCase();
  const classSkills = ALL_SKILLS.filter((s) => {
    if (s.id === 'ataque_basico') return true;
    if (s.class !== characterClass) return false;
    if (!s.subclass) return true;
    return sLower.includes(s.subclass) || s.subclass.includes(sLower);
  });

  return classSkills.length > 0 ? classSkills : [basic];
}
